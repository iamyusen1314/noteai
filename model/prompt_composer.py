@dataclass(frozen=True)
class PromptLayer:
    name: str
    content: str
    source: str = "runtime"
    dynamic: bool = False


@dataclass(frozen=True)
class ComposedPrompt:
    text: str
    domain: str
    layers: tuple[PromptLayer, ...]
    preview_complete: bool


def canonicalize_domain(domain: str | None, *, allow_other: bool = False) -> str:
    value = (domain or "").strip()
    value = _DOMAIN_ALIASES.get(value, value)
    if value in SUPPORTED_DOMAINS:
        return value
    if allow_other and re.fullmatch(r"[\w\u3400-\u9fff-]{1,24}", value):
        return value
    raise ValueError("unsupported prompt preview domain")


def neutralize_legacy_prompt_conflicts(prompt: str) -> str:
    text = prompt or ""
    for pattern, replacement in _LEGACY_REPLACEMENTS:
        text = pattern.sub(replacement, text)
    text = re.sub(
        r"(?ms)^数据来源说明：.*?(?=\n\n|\Z)",
        "数据来源说明：历史统计仅作辅助参考；当前策略以交付价值、事实可信、自然表达和人工偏好为主。",
        text,
    )
    return text


def v04_runtime_prefix(key: str, domain: str) -> str:
    return (
        f"【V0.4运行时最高优先级覆盖｜{key}｜{domain}】\n"
        "- 当前链路服务 NoteAI V0.4 复合交付目标；历史评分信号只作辅助遥测。\n"
        "- 第一目标是用户愿意发布、读者愿意收藏、事实可信、行业适配且自然好读，不是机械追分。\n"
        "- 先规划读者价值、事实边界、行业结构、标题吸引力、正文信息密度和自然表达，再参考辅助特征修缺口。\n"
        "- 不得编造价格、地址、营业时间、体验经历、医学或功效承诺；已核验事实优先。\n"
        "- 三个标题或方案必须代表不同叙事角度，正文必须服务对应标题。\n"
        "- 若基础 Prompt 与统一质量契约或请求时动态材料冲突，以后两者为准。"
    )


def compose_effective_prompt(
    key: str,
    domain: str | None,
    base_content: str,
    layers: Iterable[PromptLayer] = (),
    *,
    preview_complete: bool = False,
    allow_other_domain: bool = False,
) -> ComposedPrompt:
    canonical = canonicalize_domain(domain or "美食", allow_other=allow_other_domain)
    prefix = PromptLayer("V0.4运行时策略", v04_runtime_prefix(key, canonical), "prompt_composer")
    base = PromptLayer("可编辑基础Prompt", neutralize_legacy_prompt_conflicts(base_content), "managed_prompts")
    materialized = tuple(layer for layer in layers if (layer.content or "").strip())
    all_layers = (prefix, base, *materialized)
    return ComposedPrompt(
        text="\n\n".join(layer.content.strip() for layer in all_layers if layer.content.strip()),
        domain=canonical,
        layers=all_layers,
        preview_complete=bool(preview_complete),
    )


def dynamic_layer_labels(key: str | None = None) -> list[str]:
    if key == "semantic_features":
        return ["当前标题与正文（请求时填充，不在预览中展示）"]
    return list(_DYNAMIC_LAYER_LABELS)


def industry_preview(key: str, domain: str, content: str) -> ComposedPrompt:
    """Inspect real shared rules without importing API, users or model clients.

    These named layers expose the static inputs, not a captured full request.
    Governance, live facts and route-specific output assembly remain explicit
    omissions. Never synthesize private context to make a preview look complete.
    """
    if key == "semantic_features":
        return compose_effective_prompt(key, "通用", content, allow_other_domain=True)
    domain = canonicalize_domain(domain)
    dk = _get_dk(domain)
    content = content.replace("{domain}", domain).replace("{dk_content}", dk["content"])
    layers = [PromptLayer("行业质量契约（代码内置，只读）", _get_quality_contract(domain), "prompt_composer._get_quality_contract")]
    part = key.removesuffix("_system").rsplit("_", 1)[-1]
    if part in dk:
        layers.append(PromptLayer("行业知识（代码内置，只读）", dk[part], f"prompt_composer._DOMAIN_KNOWLEDGE.{part}"))
        if key.startswith("agent_"):
            role = {"content": "内容专家", "visual": "视觉专家", "growth": "增长专家", "user": "用户专家"}[part]
            layers.append(PromptLayer("报告输出约束（代码内置，只读）", _agent_output_contract(role, domain), "prompt_composer._agent_output_contract"))
    if key == "chat_system":
        for part in ("content", "user"):
            layers.append(PromptLayer("对话行业知识（代码内置，只读）", dk[part], f"prompt_composer._DOMAIN_KNOWLEDGE.{part}"))
    if key in {"gent_content_system", "gent_arbitrate_system", "agent_arbitrate_system", "chat_system"}:
        layers.append(PromptLayer("生成规划（请求材料待填）", render_generation_planning(
            domain, "〈请求时标题〉", "〈请求时核验事实〉", "本方案方向：〈请求时方向〉",
            "- 健身场景策略：〈请求时场景策略〉\n" if domain == "健身" else "",
        ), "prompt_composer.render_generation_planning", True))
    if key in {"gent_content_system", "gent_arbitrate_system"}:
        layers.append(PromptLayer("行业交付清单（代码内置，只读）", _GEN_CHECKLISTS[domain], "prompt_composer._GEN_CHECKLISTS"))
    if key == "gent_arbitrate_system":
        layers.append(PromptLayer("行业仲裁标准（代码内置，只读）", _get_arbitrate_standards(domain), "prompt_composer._get_arbitrate_standards"))
    return compose_effective_prompt(key, domain, content, layers)


